/* Пустые ячейки с типом «ошибка».

   Реальная выгрузка отчётности из 1С — три листа, ни одной формулы —
   давала в REX «Ошибки в ячейках: #ERR × 3468» и роняла строку «Ошибки»
   индекса до 16 из 100. Ни одной настоящей ошибки в книге не было:
   выгрузка размечает весь диапазон отчёта и каждой пустой клетке ставит
   t="e" без значения. Excel рисует их пустыми, потому что показывать
   нечего.

   Промах тянул за собой второй: такие ячейки шли в колоночную статистику
   наравне с формулами, и обычные числа в тех же колонках становились
   «значениями, вбитыми посреди формульной колонки». Семь находок из
   воздуха в книге, где формул нет вовсе.

   Набор держит обе границы: пустое с кривым типом — не ошибка, а ошибка
   со значением — по-прежнему ошибка. */
const { браузер, открыть, страница, счёт } = require('../harness');

module.exports = async function () {
    const t = счёт('Пустые ячейки с типом ошибки');
    const b = await браузер();
    const { pg, ошибки } = await открыть(b, '1c.xlsx');

    t.раздел('Считаем только настоящие ошибки');
    const л = await pg.evaluate(() => {
        const s = APP.books[0].sheets[0];
        return { ошибок: s.errorCount, виды: [...(s.errKinds || new Map()).entries()],
                 пустыхСТипом: s.badEmpty, ячеек: s.cellCount,
                 конст: s.constCount, текст: s.textCount, формул: s.formulaCount };
    });
    t.ok(л.ошибок === 1, 'настоящая ошибка одна, а не пятьдесят шесть: ' + л.ошибок);
    t.ok(л.виды.length === 1 && л.виды[0][0] === '#DIV/0!',
         'и это именно #DIV/0!: ' + JSON.stringify(л.виды));
    t.ok(л.пустыхСТипом === 56, 'пустых с типом «ошибка» насчитано 56: ' + л.пустыхСТипом);
    /* Ячейка без значения, формулы и текста — это оформление, а не данные.
       Единственная ошибка в книге сидит на формуле, поэтому в сумме её
       считает слагаемое «формул», а не «ошибок». */
    t.ok(л.ячеек === л.конст + л.текст + л.формул,
         'в «заполнено» идут только ячейки с содержимым: ' + л.ячеек +
         ' = ' + л.конст + '+' + л.текст + '+' + л.формул +
         ', а 56 размеченных пустых в счёт не пошли');

    t.раздел('Находка названа своим именем');
    const пр = await pg.evaluate(() =>
        APP.issues.map(i => ({ id: i.id, n: i.count, t: i.title, why: i.why, sev: i.severity })));
    const be = пр.find(i => i.id === 'empty-err');
    t.ok(be && be.n === 56, 'правило empty-err сработало: ' + (be || {}).n);
    t.ok(be && be.sev === 'minor', 'важность — «мелочь»: книге это не вредит');
    t.ok(be && /1С|учётн/i.test(be.why), 'сказано, откуда такие книги берутся');
    t.ok(be && /Power Query|pandas/i.test(be.why), 'сказано, кому от этого плохо');
    t.ok(be && /пересохран/i.test(be.why), 'сказано, как чинить');

    const ош = пр.find(i => i.id === 'cell-errors');
    t.ok(ош && ош.n === 1, 'cell-errors считает только настоящую ошибку: ' + (ош || {}).n);
    t.ok(!/#ERR/.test(JSON.stringify(пр)), 'заглушка #ERR в находки не попадает');

    t.раздел('Колоночная статистика не приняла пустые за формулы');
    const разрывы = пр.find(i => i.id === 'col-gap');
    t.ok(!разрывы, 'правило «разрыв в формульной колонке» молчит: формул в книге нет');

    t.раздел('Индекс здоровья не обвалился');
    const h = await pg.evaluate(() => APP.health);
    t.ok(h.scores['Ошибки'] >= 85, 'строка «Ошибки» осталась высокой: ' + h.scores['Ошибки']);
    t.ok(h.scores['Гигиена'] < 100, 'но «Гигиена» просела — находка-то настоящая: ' + h.scores['Гигиена']);

    t.раздел('На экране это видно');
    await страница(pg, 'quality');
    const текст = await pg.evaluate(() => {
        const el = [...document.querySelectorAll('.issue')]
            .find(e => /помечены как ошибочные/.test(e.textContent));
        return el ? el.textContent.replace(/\s+/g, ' ') : '';
    });
    t.ok(/помечены как ошибочные/.test(текст), 'карточка на «Качестве данных» есть');
    t.ok(/Баланс/.test(текст), 'в карточке назван лист: ' + текст.slice(0, 110));

    await pg.close();
    await b.close();
    return t.итог(ошибки);
};
